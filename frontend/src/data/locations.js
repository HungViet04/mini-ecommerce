// Get all provinces
export const getProvinces = () =>
  Object.entries(locations).map(([code, data]) => ({ code, name: data.name }));

// Get districts by province code
export const getDistricts = (provinceCode) => {
  const province = locations[provinceCode];
  if (!province) return [];
  return Object.entries(province.districts).map(([code, data]) => ({ code, name: data.name }));
};

// Get wards by province and district code
export const getWards = (provinceCode, districtCode) => {
  const province = locations[provinceCode];
  if (!province) return [];
  const district = province.districts[districtCode];
  if (!district) return [];
  return district.wards.map((code) => ({ code, name: wardNames[code] || `Phường/Xã ${code}` }));
};

// Get province name
export const getProvinceName = (code) => locations[code]?.name || code;

// Get district name
export const getDistrictName = (provinceCode, code) =>
  locations[provinceCode]?.districts[code]?.name || code;

// Get ward name
export const getWardName = (code) => wardNames[code] || `Phường/Xã ${code}`;

export default {
  locations,
  getProvinces,
  getDistricts,
  getWards,
  getProvinceName,
  getDistrictName,
  getWardName,
};
